"""
make_numbers_r1.py -- emit numbers_r1.tex (LaTeX macros) for the KBS R1 revision.

All values come from results/revision_r1_2026-11/R1_CPU.json (CPU analyses) and,
when present, R1_GPU.json (seed replicates, OLMo-2 family, native prompts).
Nothing is typed by hand. Run:  python3 make_numbers_r1.py
"""
from __future__ import annotations

import json
from pathlib import Path

PROJ = Path(__file__).resolve().parents[2]
RES = PROJ / "results" / "revision_r1_2026-11"
OUT = Path(__file__).resolve().parent / "numbers_r1.tex"

C = ["CSC", "EPIC", "MultiPICo_es", "MultiPICo_de", "MultiPICo_fr", "MultiPICo_it"]
TAG = {"CSC": "CSC", "EPIC": "EPIC", "MultiPICo_es": "ES", "MultiPICo_de": "DE",
       "MultiPICo_fr": "FR", "MultiPICo_it": "IT"}
SIZE_NAME = {"q0p5b": "0.5B", "q1p5b": "1.5B", "q3b": "3B", "q7b": "7B", "q14b": "14B", "q32b": "32B"}

lines: list[str] = ["% Auto-generated by make_numbers_r1.py -- do not edit by hand."]


def f3(x: float) -> str:
    return f"{x:.3f}"


def mac(name: str, val) -> None:
    assert name.isalpha(), name
    lines.append(f"\\newcommand{{\\{name}}}{{{val}}}")
    # plain twin without the significance dagger, for use in running text
    if isinstance(val, str) and "$^\\dagger$" in val:
        plain = val.replace("$^\\dagger$", "")
        lines.append(f"\\newcommand{{\\{name}Plain}}{{{plain}}}")


def pct(x: float, nd: int = 1) -> str:
    return f"{100 * x:.{nd}f}"


def ci(c) -> str:
    return f"[{f3(c[0])}, {f3(c[1])}]"


def pstr(p: float, b: int = 4000) -> str:
    return f"$<$1/{b + 1}" if p < 1 / (b + 1) else f"{p:.3f}"


def main() -> None:
    d = json.load(open(RES / "R1_CPU.json"))
    B = d["meta"]["B_test"]
    mac("RBootB", f"{B:,}".replace(",", "{,}"))
    mac("RPfloor", f"1/{B + 1}")

    # ---------------- S1 strata ----------------
    for c in C:
        t = TAG[c]
        s = d["S1_strata"][c]
        mac(f"NdistDis{t}", s["n_distinct_dis"])
        mac(f"FracUnan{t}", pct(s["frac_unanimous"]))
        for lab, L in (("low", "Low"), ("mid", "Mid"), ("high", "High")):
            mac(f"Nstr{L}{t}", f"{s[lab]['n']:,}".replace(",", "{,}"))
            mac(f"Pos{L}{t}", f3(s[lab]["pos_rate"]))
            mac(f"Npos{L}{t}", s[lab]["n_pos"])
        mac(f"BaseRate{t}", f3(s["base_rate"]))

    # ---------------- primary ΔAsym Holm p (six corpora) ----------------
    raw = [d["S2_alt_strat"][c]["tercile_primary"]["p_one_sided"] for c in C]
    n = len(raw)
    order = sorted(range(n), key=lambda i: raw[i])
    adj, run = [0.0] * n, 0.0
    for r, i in enumerate(order):
        run = max(run, min(1.0, raw[i] * (n - r)))
        adj[i] = run
    for c, a in zip(C, adj):
        mac(f"PrimPHolm{TAG[c]}", pstr(a, B) if a > 0 else f"$<$1/{B + 1}")
    c2b = json.load(open(PROJ / "results/revision_gpu_2026-09/round1_analysis/C2b_v5.json"))
    for c in C:
        pc = c2b["per_corpus"][c]
        ph = float(pc["p_holm"])
        mac(f"NullPHolm{TAG[c]}", "$<$1/1001" if ph == 0 else f"{ph:.3f}")
        mac(f"NullMean{TAG[c]}", f3(float(pc["null_mean"])))
        mac(f"NullExpl{TAG[c]}", pct(float(pc["null_explained_frac"])))
        mac(f"NullExcess{TAG[c]}", f3(float(pc["noise_corrected_excess"])))

    # ---------------- robustness (S2-S5) ----------------
    for c in C:
        t = TAG[c]
        s2 = d["S2_alt_strat"][c]
        mac(f"RobPrim{t}", f3(s2["tercile_primary"]["dasym"]))
        mac(f"RobPrimCI{t}", ci(s2["tercile_primary"]["ci95"]))
        mac(f"RobUnan{t}", f3(s2["unanimous_vs_split"]["dasym"]))
        mac(f"RobUnanCI{t}", ci(s2["unanimous_vs_split"]["ci95"]))
        mac(f"RobUnanP{t}", pstr(s2["unanimous_vs_split"]["p_one_sided"], B))
        mac(f"RobMed{t}", f3(s2["median_split"]["dasym"]))
        mac(f"RobMedCI{t}", ci(s2["median_split"]["ci95"]))
        s3 = d["S3_strat_uncertainty"][c]
        mac(f"RobStrCI{t}", ci(s3["ci95"]))
        mac(f"RobStrP{t}", pstr(s3["p_one_sided"], B))
        mac(f"RobStrLo{t}", f3(s3["ci95"][0]))
        s4 = d["S4_reweight"][c]["label_x_length_reweighted"]
        mac(f"RobRew{t}", f3(s4["dasym"]))
        mac(f"RobRewCI{t}", ci(s4["ci95"]))
        s5 = d["S5_full_range"][c]
        mac(f"SlopeLow{t}", f3(s5["slope_low_per_doubling"]))
        mac(f"SlopeHigh{t}", f3(s5["slope_high_per_doubling"]))
        mac(f"SlopeDiff{t}", f3(s5["slope_diff"]))
        mac(f"SlopeDiffCI{t}", ci(s5["slope_diff_ci95"]))
        mac(f"SlopeDiffP{t}", pstr(s5["p_one_sided"], B))
        ref = s5["common_reference_lower"]
        mac(f"RefSize{t}", SIZE_NAME[ref])
        rt = s5.get("common_reference_test", s5["endpoints"]["q0p5b->q32b"])
        mac(f"RobRef{t}", f3(rt["dasym"]))
        mac(f"RobRefCI{t}", ci(rt["ci95"]))
        for a, A in (("q1p5b", "OneFive"), ("q3b", "Three")):
            e = s5["endpoints"][f"{a}->q32b"]
            mac(f"RobEnd{A}{t}", f3(e["dasym"]))
            mac(f"RobEnd{A}CI{t}", ci(e["ci95"]))
        fp = s5["fully_parsed_only"]
        mac(f"RobParsed{t}", f3(fp["dasym"]))
        mac(f"RobParsedCI{t}", ci(fp["ci95"]))
        op = s5["output_profile"]
        for sz, S in (("q0p5b", "Small"), ("q32b", "Large")):
            mac(f"YesRate{S}{t}", f3(op[sz]["yes_rate"]))
            mac(f"BALow{S}{t}", f3(op[sz]["balacc_low"]))
            mac(f"RecPosLow{S}{t}", f3(op[sz]["recall_pos_low"]))
            mac(f"RecNegLow{S}{t}", f3(op[sz]["recall_neg_low"]))
        mac(f"ParseFailSmall{t}", pct(op["q0p5b"]["frac_n_valid_lt10"]))
    mac("ParseFailSmallMax", pct(max(d["S5_full_range"][c]["output_profile"]["q0p5b"]["frac_n_valid_lt10"] for c in C)))

    # ---------------- S6 CSC bound ----------------
    s6 = d["S6_csc_bound"]
    mac("CSCnClipSample", s6["sample_var_ratio_gt1"])
    mac("CSCpctClipSample", pct(s6["sample_var_ratio_gt1"] / s6["n_items"]))
    mac("CSCnClipPop", s6["population_var_ratio_gt1"])
    mac("CSCnFloor", s6["n_floor_hit"])
    mac("CSCpctFloor", pct(s6["frac_floor_hit"]))
    mac("CSCrhoPopSample", f3(s6["spearman_ddof1_vs_ddof0"]))
    mac("CSCtercAgreePop", pct(s6["tercile_agreement_ddof1_vs_ddof0"]))
    mac("CSCdasymPop", f3(s6["dasym_population_variance"]["dasym"]))
    mac("CSCdasymPopCI", ci(s6["dasym_population_variance"]["ci95"]))
    mac("CSCkMin", s6["k_i_min"])
    mac("CSCkMax", s6["k_i_max"])

    # ---------------- S7 400-item subsampling ----------------
    for c in ("CSC", "EPIC"):
        t = TAG[c]
        s7 = d["S7_sub400"][c]
        mac(f"SubSD{t}", f3(s7["sub400_sd"]))
        mac(f"SubLo{t}", f3(s7["sub400_p2.5"]))
        mac(f"SubHi{t}", f3(s7["sub400_p97.5"]))
        mac(f"OrigFourRegen{t}", f3(s7["regen_on_original_400"]["dasym"]))
        mac(f"OrigFourRegenCI{t}", ci(s7["regen_on_original_400"]["ci95"]))
    mac("SubFracGeCSC", pct(d["S7_sub400"]["CSC"]["frac_sub400_ge_0.242"]))
    mac("SubSDmin", f3(min(d["S7_sub400"][c]["sub400_sd"] for c in C)))
    mac("SubSDmax", f3(max(d["S7_sub400"][c]["sub400_sd"] for c in C)))

    # ---------------- S8 escalation ----------------
    names = {"contraction_probe": "Probe", "entropy_0p5b": "Ent", "one_minus_dis": "Hum",
             "supervised_calibrated_confidence": "Cal", "supervised_grouping_loss_natural": "GL"}
    for c in C:
        t = TAG[c]
        s8 = d["S8_escalation"][c]
        mac(f"NWrong{t}", f"{s8['n_small_wrong']:,}".replace(",", "{,}"))
        mac(f"NFix{t}", f"{s8['n_fix']:,}".replace(",", "{,}"))
        for k, N in names.items():
            v = s8["on_small_wrong"][k]
            sig = v["ci95"][0] > 0.5 or v["ci95"][1] < 0.5
            mac(f"Esc{N}{t}", f3(v["AUROC"]) + ("$^\\dagger$" if sig else ""))
            mac(f"Esc{N}CI{t}", ci(v["ci95"]))
        for k, N in (("contraction_probe", "Probe"), ("entropy_0p5b", "Ent"), ("one_minus_dis", "Hum")):
            v = s8["all_items"][k]
            sig = v["ci95"][0] > 0.5 or v["ci95"][1] < 0.5
            mac(f"All{N}{t}", f3(v["AUROC"]) + ("$^\\dagger$" if sig else ""))
            mac(f"All{N}CI{t}", ci(v["ci95"]))
        e = s8["error_types"]
        mac(f"NFP{t}", f"{e['n_false_pos']:,}".replace(",", "{,}"))
        mac(f"NFN{t}", f"{e['n_false_neg']:,}".replace(",", "{,}"))
        mac(f"FixFP{t}", f3(e["fix_rate_false_pos"]))
        mac(f"FixFN{t}", f3(e["fix_rate_false_neg"]))
        mac(f"EntFP{t}", f3(e["mean_entropy_false_pos"]))
        if e["mean_entropy_false_neg"] == e["mean_entropy_false_neg"]:
            mac(f"EntFN{t}", f3(e["mean_entropy_false_neg"]))
        for nm, N in (("phi3_mini", "Phi"), ("smollm2_1p7b", "Smol"), ("stablelm_3b", "Stab"),
                      ("sampling_noise", "Noise")):
            v = s8["diversity"][nm]
            mac(f"Div{N}{t}", f3(v["AUROC_control"]))

    ents = [d["S8_escalation"][c]["all_items"]["entropy_0p5b"]["AUROC"] for c in C]
    mac("AllEntMinVal", f3(min(ents)))
    mac("AllEntMaxVal", f3(max(ents)))

    # ---------------- S9 AUBAC + global Holm ----------------
    for c in C:
        t = TAG[c]
        a = d["S9_aubac"][c]
        mac(f"AUBACRand{t}", f3(a["random_mean"]))
        for k, N in (("contraction", "Probe"), ("confidence", "Conf"), ("one_minus_dis", "Hum")):
            v = a[k]
            sig = v["delta_ci95"][0] > 0 or v["delta_ci95"][1] < 0
            mac(f"AUBAC{N}{t}", f3(v["aubac"]) + ("$^\\ast$" if sig else ""))
            mac(f"AUBACD{N}{t}", f"{v['delta_vs_random']:+.3f}")
            mac(f"AUBACD{N}CI{t}", ci(v["delta_ci95"]))
    gh = d["S9_global_holm"]
    mac("GHn", gh["n_tests"])
    fam_names = {"capacity_vs_control": "Ctrl", "probe_auroc_vs_0.5": "ProbeAUC",
                 "aubac_probe_vs_random": "AUBAC", "noise_null_excess": "Null",
                 "full_range_slope": "Slope"}
    for fam, N in fam_names.items():
        tests = [x for x in gh["tests"] if x["family"] == fam]
        mac(f"GH{N}n", len(tests))
        mac(f"GH{N}sig", sum(x["sig_global_05"] for x in tests))
    for c in C:
        t = TAG[c]
        ctrl = [x for x in gh["tests"] if x["family"] == "capacity_vs_control" and x["corpus"] == c]
        mac(f"GHCtrlSig{t}", f"{sum(x['sig_global_05'] for x in ctrl)}/{len(ctrl)}")
        nul = [x for x in gh["tests"] if x["family"] == "noise_null_excess" and x["corpus"] == c][0]
        mac(f"GHNullP{t}", pstr(nul["p_holm_global"], 1000) if nul["p_holm_global"] > 0 else "$<$0.001")
        ab = [x for x in gh["tests"] if x["family"] == "aubac_probe_vs_random" and x["corpus"] == c][0]
        mac(f"GHAUBACP{t}", f"{ab['p_holm_global']:.3f}" if ab["p_holm_global"] > 0 else "$<$0.001")

    # ---------------- S10 frontier ----------------
    MOD = {"GPT-4o-mini": "Mini", "Claude-Haiku-4.5": "Haiku", "GPT-4.1": "Gpt", "Claude-Opus-4.8": "Opus"}
    for key, v in d["S10_frontier"].items():
        corpus, model = key.split("|")
        t, m = TAG[corpus], MOD[model]
        mac(f"FBA{m}{t}", f3(v["balacc_low"]))
        mac(f"FBACI{m}{t}", ci(v["balacc_low_ci95"]))
        mac(f"FFPR{m}{t}", f3(v["fpr_low"]))
        mac(f"FFNR{m}{t}", f3(v["fnr_low"]))
        mac(f"FECE{m}{t}", f3(v["ece_verbal"]))
        mac(f"FRho{m}{t}", f3(v["rho_Uvc_dis"]))
        mac(f"FRhoCI{m}{t}", ci(v["rho_Uvc_dis_ci95"]))
        mac(f"FAuc{m}{t}", f3(v["auroc_Uvc_high_dis"]))
        if model == "GPT-4.1":
            mac(f"FNlow{t}", v["n_low"])
            mac(f"FNposLow{t}", v["n_pos_low"])
        if "rho_Ulp_dis" in v:
            mac(f"FRhoLp{m}{t}", f3(v["rho_Ulp_dis"]))
            mac(f"FAucLp{m}{t}", f3(v["auroc_Ulp_high_dis"]))
    rhos = [v["rho_Uvc_dis"] for v in d["S10_frontier"].values()]
    mac("FRhoMax", f3(max(rhos)))
    mac("FRhoMin", f3(min(rhos)))

    # ---------------- S11 sharpness ----------------
    for c in C:
        t = TAG[c]
        s = d["S11_sharpness"][c]["high"]
        mac(f"SharpHighSmall{t}", f3(s["q0p5b"]["sharpness_mean_abs_p_minus_half"]))
        mac(f"SharpHighLarge{t}", f3(s["q32b"]["sharpness_mean_abs_p_minus_half"]))
        mac(f"SharpHighHuman{t}", f3(s["q32b"]["human_sharpness"]))
        mac(f"BiasHighLarge{t}", f"{s['q32b']['mean_signed_bias_p_minus_ph']:+.3f}")
        mac(f"BiasSqHighLarge{t}", f3(s["q32b"]["bias_sq_term"]))
        mac(f"VarHighLarge{t}", f3(s["q32b"]["var_term"]))

    # ---------------- S12 run variance ----------------
    for c in C:
        t = TAG[c]
        s = d["S12_run_variance"][c]
        mac(f"RunOne{t}", f3(s["dasym_run1"]))
        mac(f"RunTwo{t}", f3(s["dasym_run2"]))
        mac(f"RunAgree{t}", pct(s["item_agreement_0p5b_runs"]))

    # ---------------- semantic discrepancy (Appendix B) ----------------
    e2 = json.load(open(PROJ / "results/llm_e2/e2_summary_phase1.json"))["results"]
    csc = [r for r in e2 if r["dataset"] == "CSC"]
    mac("DeltaErrRhoMaxCSC", f3(max(abs(r["rho_delta_error"]["rho"]) for r in csc)))
    mac("DeltaErrPartialMaxCSC", f3(max(abs(r["partial_delta_error_ctrl_humandis"]) for r in csc)))
    mac("DeltaDisRhoCSC", f3(csc[0]["rho_delta_humandis"]["rho"]))
    mac("DeltaUvRhoMaxCSC", f3(max(r["rho_delta_Uverbal"]["rho"] for r in csc)))

    # ---------------- GPU results (filled only when R1_GPU.json exists) ----------------
    g = RES / "R1_GPU.json"
    if g.exists():
        gd = json.load(open(g))
        for k, v in gd.get("macros", {}).items():
            mac(k, v)

    OUT.write_text("\n".join(lines) + "\n")
    print(f"wrote {OUT} ({len(lines) - 1} macros)")


if __name__ == "__main__":
    main()
